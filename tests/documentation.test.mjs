// Documentation contracts only; no DSH/browser or physical-input acceptance.
import assert from 'node:assert/strict';
import { readFile, access } from 'node:fs/promises';
import test from 'node:test';
import vm from 'node:vm';

const root = new URL('../', import.meta.url);
const read = name => readFile(new URL(name, root), 'utf8');
const pkg = JSON.parse(await read('package.json'));
const source = await read('lib/client.js');
const marker = "    return createChatZoomClient(require('react'));";
assert.equal(source.split(marker).length, 2);
let api;
vm.runInNewContext(source.replace(marker,
  '    return { MIN_PERCENT, MAX_PERCENT, DEFAULT_PERCENT, STEP_PERCENT, STORAGE_KEY, KEYBOARD_STORAGE_KEY, WHEEL_STORAGE_KEY, DEFAULT_KEYBOARD, DEFAULT_WHEEL, HINT_DURATION_MS, validateKeyboardConfig, validateWheelConfig };'), {
  window: { __ModuleLoader__: { load(definition) { api = definition.factory(() => { throw new Error('documentation check must not import React'); }); } } }
});
const plain = value => JSON.parse(JSON.stringify(value));
const documents = ['README.md', 'PRIVACY.md', 'CONTRIBUTING.md', 'MARKET.md', 'CHANGELOG.md', 'VALIDATION.md'];

test('bilingual current-version notices and newest changelog agree with the package', async () => {
  const readme = await read('README.md');
  assert.ok(readme.includes(`当前 main 开发版本：v${pkg.version}（尚未发布安装包）`));
  assert.ok(readme.includes(`Current main development version: v${pkg.version} (no released package yet)`));
  const privacy = await read('PRIVACY.md');
  assert.ok(privacy.includes(`v${pkg.version}（未发布）`));
  assert.ok(privacy.includes(`v${pkg.version} on main (unreleased)`));
  const latest = (await read('CHANGELOG.md')).match(/^## (.+)$/m)?.[1];
  assert.ok(latest?.startsWith(`v${pkg.version} — Unreleased / 未发布`));
});

test('both privacy JSON examples use actual storage keys, schemas and runtime defaults', async () => {
  const privacy = await read('PRIVACY.md');
  const examples = [...privacy.matchAll(/```json\r?\n([\s\S]*?)\r?\n```/g)].map(match => JSON.parse(match[1]));
  assert.equal(examples.length, 2, 'one decoded-default example per language');
  const expected = {
    [api.STORAGE_KEY]: String(api.DEFAULT_PERCENT),
    [api.KEYBOARD_STORAGE_KEY]: plain(api.DEFAULT_KEYBOARD),
    [api.WHEEL_STORAGE_KEY]: plain(api.DEFAULT_WHEEL)
  };
  for (const value of examples) {
    assert.deepEqual(value, expected);
    assert.equal(api.validateKeyboardConfig(value[api.KEYBOARD_STORAGE_KEY]).ok, true);
    assert.equal(api.validateWheelConfig(value[api.WHEEL_STORAGE_KEY]).ok, true);
  }
});

test('documented limits, hint duration and custom-binding example match the client', async () => {
  const readme = await read('README.md');
  assert.ok(readme.includes(`${api.MIN_PERCENT}%–${api.MAX_PERCENT}%`));
  assert.ok(readme.includes(`**${api.DEFAULT_PERCENT}%**`));
  assert.ok(readme.includes(`**${api.STEP_PERCENT} 个百分点**`));
  assert.ok(readme.includes(`**${api.HINT_DURATION_MS / 1000} seconds**`));
  assert.ok(readme.includes('`Alt+J`、`Alt+K`、`F9`'));
  assert.ok(readme.includes('`Alt+J`, `Alt+K`, `F9`'));
  assert.equal(api.validateKeyboardConfig({ version:1, bindings:{ zoomIn:'Alt+J', zoomOut:'Alt+K', reset:'F9' } }).ok, true);
  assert.ok(readme.includes('releases/download/v0.1.0/dsh-plugin-chat-zoom-0.1.0.tgz'));
  assert.ok(!readme.includes(`/releases/download/v${pkg.version}/`), 'do not invent a development release asset');
});

test('all local document links and package entry/allowlist files exist without shipping tests', async () => {
  for (const name of documents) {
    for (const [, link] of (await read(name)).matchAll(/\]\(([^)]+)\)/g)) {
      const target = link.split('#')[0];
      if (!target || /^(https?:|mailto:)/.test(target)) continue;
      const url = new URL(decodeURIComponent(target), new URL(name, root));
      assert.ok(url.href.startsWith(root.href), `link must remain inside the plugin: ${name}`);
      await access(url);
    }
  }
  for (const name of [...pkg.files, ...Object.values(pkg.exports), pkg.dsh.bundle.patch]) await access(new URL(name, root));
  assert.ok(pkg.files.every(name => !name.startsWith('tests/') && !name.endsWith('.tgz')));
  assert.equal(pkg.dependencies, undefined);
  assert.equal(pkg.devDependencies, undefined);
  assert.equal(pkg.scripts, undefined);
});

test('maintained client comments do not imply a missing generator or split-source checkout', async () => {
  assert.doesNotMatch(source, /Generated by build-client\.mjs|^\/\/ src\//m);
  const contributing = await read('CONTRIBUTING.md');
  assert.ok(contributing.includes('node --test tests/*.test.mjs'));
});
